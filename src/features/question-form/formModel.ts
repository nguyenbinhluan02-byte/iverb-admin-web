import { z } from 'zod'
import { orderedWords, sentenceOf } from '@/lib/question'
import type {
  AnswerKey,
  AudioMeta,
  Question,
  QuestionContent,
  QType,
  Voice,
} from '@/services/questions'

export interface OptionValue {
  text: string
  correct: boolean
}

export type AudioSource = 'tts' | 'file'

/** A chosen file, uploaded on save. */
export interface PickedAudio {
  file: File
  durationSec: number
}

// Flat form state for all types (design: "New / Edit question").
export interface FormValues {
  type: QType
  prompt: string
  options: OptionValue[] // single / multi
  sentence: string // fill: with ___; order: the correct sentence
  answer: string // fill: accepted answers separated by "/"
  hint: string // fill
  // Listening card (design Oct 31). Dictation is always listening; reorder never.
  listening: boolean
  audioSource: AudioSource
  voice: Voice
  transcript: string // dictation: the sentence users write
  picked: PickedAudio | null // file chosen, not uploaded yet
  audioUrl: string // current file (saved, or generated by a preview)
  audioMeta: AudioMeta | null
  explanation: string
  authorName: string
  date: string | null
}

export const VOICES: { value: Voice; label: string }[] = [
  { value: 'us-f', label: 'US · Female' },
  { value: 'us-m', label: 'US · Male' },
  { value: 'uk-f', label: 'UK · Female' },
  { value: 'uk-m', label: 'UK · Male' },
]

/** Listening applies: dictation always, reorder never. */
export const hasListening = (v: Pick<FormValues, 'type' | 'listening'>) =>
  v.type === 'dictation' || (v.listening && v.type !== 'order')

/** The current audioUrl is the TTS file of this voice + transcript. */
export const ttsUpToDate = (
  v: Pick<FormValues, 'audioUrl' | 'audioMeta' | 'voice' | 'transcript'>,
  generatedFor: string | null,
) => !!v.audioUrl && v.audioMeta?.source === 'tts' && generatedFor === ttsKey(v.voice, v.transcript)

export const ttsKey = (voice: Voice, transcript: string) => `${voice}|${transcript.trim()}`

export const MIN_OPTIONS = 2
export const MAX_OPTIONS = 6
export const BLANK = '___'

export function emptyForm(date: string | null, authorName: string): FormValues {
  return {
    type: 'single',
    prompt: '',
    options: Array.from({ length: 4 }, () => ({ text: '', correct: false })),
    sentence: '',
    answer: '',
    hint: '',
    listening: false,
    audioSource: 'tts',
    voice: 'us-f',
    transcript: '',
    picked: null,
    audioUrl: '',
    audioMeta: null,
    explanation: '',
    authorName,
    date,
  }
}

export function fromQuestion(q: Question, date: string | null): FormValues {
  const correct = new Set(q.answer_key?.correct ?? [])
  return {
    type: q.type,
    prompt: q.prompt,
    options: (q.content.options ?? []).map((o) => ({ text: o.text, correct: correct.has(o.id) })),
    sentence: q.type === 'order' ? orderedWords(q).join(' ') : (sentenceOf(q) ?? ''),
    answer: (q.answer_key?.accepted ?? []).join(' / '),
    hint: q.content.hint ?? '',
    listening: !!q.content.audio_url,
    audioSource: q.content.audio_meta?.source ?? (q.content.audio_url ? 'file' : 'tts'),
    voice: q.content.audio_meta?.voice ?? 'us-f',
    transcript: q.answer_key?.transcript ?? q.answer_key?.sentence ?? '',
    picked: null,
    audioUrl: q.content.audio_url ?? '',
    audioMeta: q.content.audio_meta ?? null,
    explanation: q.explanation ?? '',
    authorName: q.author?.name ?? '',
    date,
  }
}

/**
 * Switching type keeps what still fits; single keeps only the first correct
 * option; dictation turns listening on (reorder ignores it when saving).
 */
export function switchType(values: FormValues, type: QType): Partial<FormValues> {
  if (type === 'dictation') return { type, listening: true }
  if (type !== 'single') return { type }
  let seen = false
  const options = values.options.map((o) => {
    const correct = o.correct && !seen
    if (correct) seen = true
    return { ...o, correct }
  })
  return { type, options }
}

export const words = (sentence: string) => sentence.trim().split(/\s+/).filter(Boolean)
export const filledOptions = (values: FormValues) => values.options.filter((o) => o.text.trim())
export const acceptedAnswers = (answer: string) => [
  ...new Set(
    answer
      .split('/')
      .map((a) => a.trim())
      .filter(Boolean),
  ),
]

// Everything needed to schedule (design `valid(f)`).
const publishable = z
  .object({
    type: z.enum(['single', 'multi', 'fill', 'order', 'dictation']),
    prompt: z.string().trim().min(1),
    options: z.array(z.object({ text: z.string(), correct: z.boolean() })),
    sentence: z.string(),
    answer: z.string(),
    listening: z.boolean(),
    audioSource: z.enum(['tts', 'file']),
    transcript: z.string(),
    picked: z.unknown(),
    audioUrl: z.string(),
    audioMeta: z.unknown(),
  })
  .superRefine((v, ctx) => {
    const fail = (message: string) => ctx.addIssue({ code: 'custom', message })
    if (hasListening(v)) {
      if (!v.transcript.trim())
        fail(v.type === 'dictation' ? 'Add the sentence users must write.' : 'Add the transcript.')
      if (v.audioSource === 'file' && !hasFile(v)) fail('Choose an audio file.')
    }
    if (v.type === 'dictation') {
      if (words(v.transcript).length < 3) fail('The sentence needs at least 3 words.')
    } else if (v.type === 'single' || v.type === 'multi') {
      const filled = v.options.filter((o) => o.text.trim())
      const correct = filled.filter((o) => o.correct).length
      if (filled.length < MIN_OPTIONS) fail('Add at least two options.')
      if (v.type === 'single' ? correct !== 1 : correct < 1) fail('Mark the correct answer.')
      if (new Set(filled.map((o) => o.text.trim().toLowerCase())).size !== filled.length)
        fail('Options must be different.')
    } else if (v.type === 'fill') {
      if (!v.sentence.includes(BLANK)) fail(`Add ${BLANK} where the blank should go.`)
      if (!acceptedAnswers(v.answer).length) fail('Add the correct answer.')
    } else if (words(v.sentence).length < 3) {
      fail('The sentence needs at least 3 words.')
    }
  })

export function canPublish(values: FormValues): boolean {
  return publishable.safeParse(values).success
}

/** An uploaded file is there (picked now, or saved before). */
const hasFile = (v: { picked: unknown; audioUrl: string; audioMeta: unknown }) =>
  !!v.picked || (!!v.audioUrl && (v.audioMeta as AudioMeta | null)?.source === 'file')

/** Errors that block publishing, for the form (first one is shown). */
export function publishErrors(values: FormValues): string[] {
  const result = publishable.safeParse(values)
  return result.success ? [] : result.error.issues.map((i) => i.message)
}

export function canSaveDraft(values: FormValues): boolean {
  if (!values.prompt.trim()) return false
  // The server needs the audio of a dictation even in a draft.
  if (values.type === 'dictation')
    return values.audioSource === 'tts' ? !!values.transcript.trim() : hasFile(values)
  return true
}

/** Whether the key part alone is complete (a draft stores the key only then). */
function keyComplete(values: FormValues): boolean {
  return publishable.safeParse({ ...values, prompt: 'x' }).success
}

const sameJson = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b)

// Shuffle so the tiles never start in the correct order (when possible).
export function shuffleTiles<T>(items: T[], random = Math.random): T[] {
  if (items.length < 2) return [...items]
  for (;;) {
    const out = [...items]
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1))
      ;[out[i], out[j]] = [out[j], out[i]]
    }
    if (out.some((x, i) => x !== items[i]) || new Set(items).size === 1) return out
  }
}

/**
 * content + answer_key for the RPC. When the visible question did not change,
 * the original JSON is sent back as is (stable ids, same tile shuffle), so an
 * answered question passes the backend's `has_answers` check.
 */
export function buildPayload(
  values: FormValues,
  original: Question | null,
  audio: { url: string; meta: AudioMeta } | null = null,
  random = Math.random,
): { content: QuestionContent; answer_key: AnswerKey | null } {
  const built = withAudio(build(values, random), values, audio)
  if (original && original.type === values.type) {
    const before = fromQuestion(original, null)
    const unchanged =
      values.type === 'single' || values.type === 'multi'
        ? sameJson(clean(before.options), clean(values.options))
        : values.type === 'fill'
          ? sameJson(built.content, original.content) &&
            sameJson(built.answer_key, original.answer_key)
          : sameJson(words(before.sentence), words(values.sentence))
    if (unchanged) return { content: original.content, answer_key: original.answer_key }
  }
  return { ...built, answer_key: keyComplete(values) ? built.answer_key : null }
}

// Listening fields: audio in the content, transcript / sentence in the key.
function withAudio(
  built: { content: QuestionContent; answer_key: AnswerKey },
  values: FormValues,
  audio: { url: string; meta: AudioMeta } | null,
) {
  if (!hasListening(values)) return built
  const content = audio
    ? { ...built.content, audio_url: audio.url, audio_meta: audio.meta }
    : built.content
  const transcript = values.transcript.trim()
  const answer_key =
    values.type === 'dictation'
      ? { sentence: transcript }
      : transcript
        ? { ...built.answer_key, transcript }
        : built.answer_key
  return { content, answer_key }
}

const clean = (options: OptionValue[]) =>
  options.filter((o) => o.text.trim()).map((o) => ({ text: o.text.trim(), correct: o.correct }))

function build(
  values: FormValues,
  random: () => number,
): { content: QuestionContent; answer_key: AnswerKey } {
  if (values.type === 'dictation') return { content: {}, answer_key: {} }
  if (values.type === 'single' || values.type === 'multi') {
    const options = clean(values.options).map((o, i) => ({ id: 'abcdef'[i], ...o }))
    return {
      content: { options: options.map(({ id, text }) => ({ id, text })) },
      answer_key: { correct: options.filter((o) => o.correct).map((o) => o.id) } as AnswerKey,
    }
  }
  if (values.type === 'fill') {
    const i = values.sentence.indexOf(BLANK)
    const before = (i >= 0 ? values.sentence.slice(0, i) : values.sentence).trim()
    const after = i >= 0 ? values.sentence.slice(i + BLANK.length).trim() : ''
    const content: QuestionContent = { before, after }
    if (values.hint.trim()) content.hint = values.hint.trim()
    return { content, answer_key: { accepted: acceptedAnswers(values.answer) } as AnswerKey }
  }
  const tiles = words(values.sentence).map((text, i) => ({ id: `t${i + 1}`, text }))
  return {
    content: { tiles: shuffleTiles(tiles, random) },
    answer_key: { order: tiles.map((t) => t.id) } as AnswerKey,
  }
}
